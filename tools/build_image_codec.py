"""Bundle locked image encoders into a dependency-free Serverless module."""
import json
import os
from pathlib import Path
import subprocess
ROOT=Path(__file__).resolve().parents[1]
out=ROOT/'serverless/tgcloud/lib/image-codec.js'
versions=json.loads((ROOT/'serverless/package.json').read_text())['devDependencies']
work=ROOT/'work'
work.mkdir(exist_ok=True)
encoder=(ROOT/'serverless/node_modules/jpeg-js/lib/encoder.js').read_text()
# The encoder's only Node dependency is its output constructor. Keep bytes
# identical while returning the Uint8Array accepted by the hosted SDK.
assert encoder.count('Buffer.from(byteout)')==1
(work/'jpeg-encoder.cjs').write_text(encoder.replace('Buffer.from(byteout)','new Uint8Array(byteout)'))
(work/'image-codec-entry.mjs').write_text("""import {deflate,inflate} from '../serverless/node_modules/pako/dist/pako.esm.mjs';
import encode from './jpeg-encoder.cjs';
export {deflate as zlibSync,inflate as unzlibSync};
export function jpegSync(rgb,width,height,quality=88){
 const rgba=new Uint8Array(width*height*4);
 for(let i=0,j=0;i<rgb.length;i+=3,j+=4){rgba[j]=rgb[i];rgba[j+1]=rgb[i+1];rgba[j+2]=rgb[i+2];rgba[j+3]=255;}
 return encode({data:rgba,width,height},quality).data;
}
""")
subprocess.run(['npm','exec','--yes','--ignore-scripts','--package=esbuild@0.25.12','--','esbuild',
                'work/image-codec-entry.mjs','--bundle','--minify','--format=esm','--platform=neutral',
                '--target=es2020','--legal-comments=inline','--outfile='+str(out)],cwd=ROOT,
               env=dict(os.environ,npm_config_cache=str(work/'npm-cache')),check=True)
out.write_text('// Bundled pako (MIT/Zlib), jpeg-js (BSD-3-Clause): tools/licenses/. Generated by tools/build_image_codec.py.\n'
               +f"export const CODEC_SOURCE='pako@{versions['pako']}+jpeg-js@{versions['jpeg-js']}';\n"+out.read_text())
