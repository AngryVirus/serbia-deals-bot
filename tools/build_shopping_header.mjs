// Compile the reviewed artwork to an embedded palette; no runtime HTTP/assets.
import {readFileSync,writeFileSync} from 'node:fs';
import {deflateSync} from 'node:zlib';
const width=960,height=320;
// First: magick assets/shopping-header.png -depth 8 rgb:work/shopping-header.rgb
const rgb=readFileSync(process.argv[2]||'work/shopping-header.rgb');
if(rgb.length!==width*height*3)throw Error('Unexpected artwork dimensions');
const palette=[],colors=new Map(),indexed=Buffer.alloc(width*height);
for(let p=0;p<indexed.length;p++){
 const offset=p*3,key=rgb.readUIntBE(offset,3);
 if(!colors.has(key)){colors.set(key,colors.size);palette.push(...rgb.subarray(offset,offset+3));}
 if(colors.size>256)throw Error('Artwork palette exceeds 256 colors');
 indexed[p]=colors.get(key);
}
writeFileSync('serverless/tgcloud/lib/image-header.js','// Generated by tools/build_shopping_header.mjs from assets/shopping-header.png.\nexport const HEADER='+JSON.stringify({width,height,palette,compressed:[...deflateSync(indexed)]})+';\n');
